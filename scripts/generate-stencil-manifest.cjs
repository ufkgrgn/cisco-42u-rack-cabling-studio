const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const stencilDir = path.join(root, 'assets', 'stencils');
const output = path.join(root, 'js', 'stencil-manifest.js');

const files = fs.existsSync(stencilDir)
  ? fs.readdirSync(stencilDir, { withFileTypes: true })
      .filter(entry => entry.isFile() && /\.svg$/i.test(entry.name))
      .map(entry => entry.name)
      .sort((a, b) => a.localeCompare(b, 'en'))
  : [];

const source = `// Generated by scripts/generate-stencil-manifest.cjs. Do not edit by hand.\n` +
  `(function () { window.RACK_STENCIL_MANIFEST = Object.freeze(${JSON.stringify(files, null, 2)}); }());\n`;

fs.writeFileSync(output, source, 'utf8');
console.log(`[stencils] Generated ${path.relative(root, output)} with ${files.length} SVG files`);
